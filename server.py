#!/usr/bin/env python3
"""Local server for the Spanish course site.

Serves site/ on http://127.0.0.1:8765 and records progress into the Obsidian
vault (Progress/progress.json + generated Dashboard, Quiz Log, Study Log and
Practice notes) so other Claude sessions can see where you're at.

    python3 server.py           # start the site
    python3 server.py --open    # start and open the browser
    python3 server.py --regen   # just rebuild Dashboard.md from progress.json
"""
import hashlib
import json
import subprocess
import sys
import threading
import urllib.parse
import webbrowser
from datetime import date, datetime, timedelta
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build import COURSE, VAULT, note_name  # noqa: E402

PORT = 8765
PROGRESS = VAULT / "Progress"
STATE_FILE = PROGRESS / "progress.json"
FLASH_DAYS = [0, 1, 3, 7, 14, 30]  # flashcard box → days until it comes back (box 0 = still learning)
LOCK = threading.Lock()
PASS_QUIZ = 0.8
BY_WEEK = {w["week"]: w for w in COURSE}
SAY_DIR = VAULT / "Media" / "audio" / "say"  # on-demand clips for Vocabulary Bank words (browsers without a Spanish voice)
SAY_SLOTS = threading.Semaphore(2)
SAY_VOICES = {"mx": "es-MX-DaliaNeural", "es": "es-ES-ElviraNeural"}  # ?v=es for the Spain version of a word
SAY_CODE = "import asyncio, sys, edge_tts; asyncio.run(edge_tts.Communicate(sys.argv[1], sys.argv[3], rate='-10%').save(sys.argv[2]))"


def now():
    return datetime.now().strftime("%Y-%m-%d %H:%M")


def load_state():
    if STATE_FILE.exists():
        return json.loads(STATE_FILE.read_text(encoding="utf-8"))
    return {"started": now()[:10], "weeks": {}, "sessions": [], "activity": []}


def save_state(state):
    PROGRESS.mkdir(parents=True, exist_ok=True)
    tmp = STATE_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(STATE_FILE)


def week_complete(w):
    return bool(w.get("lesson_done") and w.get("worksheet_attempts")
                and w.get("quiz_total") and w.get("quiz_best", 0) / w["quiz_total"] >= PASS_QUIZ
                and w.get("practice_done"))


def current_week(state):
    for w in COURSE:
        if not week_complete(state["weeks"].get(str(w["week"]), {})):
            return w["week"]
    return COURSE[-1]["week"]


def append(path, header, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(header.strip() + "\n\n", encoding="utf-8")
    with path.open("a", encoding="utf-8") as f:
        f.write(text)


def fmt_missed(missed):
    return "".join(f"\n    - {m['q']} — you: *{m.get('given') or '—'}*, correct: **{m['correct']}**" for m in missed)


def apply_event(state, ev):
    kind = ev["type"]
    ts = now()
    if kind == "session":
        minutes = max(0, int(ev.get("minutes", 0)))
        note = ev.get("note", "").strip()
        state["sessions"].append({"date": ts, "minutes": minutes, "note": note})
        append(PROGRESS / "Study Log.md", "# Study Log\nGenerated by the course site. Newest at the bottom.",
               f"- {ts} — {minutes} min" + (f" — {note}" if note else "") + "\n")
        state["activity"].append(f"{ts} — studied {minutes} min")
        return
    if kind == "vocab":  # ➕ on Palabra del día
        es, en, topic = (str(ev.get(k, "")).strip() for k in ("es", "en", "topic"))
        path = VAULT / "My Notes" / "Vocab.md"
        text = path.read_text(encoding="utf-8") if path.exists() else ""
        if f"- {es} — " not in text:
            append(path, "# Vocab\nWords I'm learning. Format: `español — English (week)`",
                   ("" if not text or text.endswith("\n") else "\n") + f"- {es} — {en} ({topic})\n")
            state["activity"].append(f"{ts} — added “{es}” to Vocab")
        return

    if kind == "flash":  # 🎴 Vocabulary Bank flashcards: each "I know it" moves a word up a box, so it comes back less often
        cards = state.setdefault("flash", {})
        known, learning = [], []
        for r in ev.get("results", []):
            es, en = str(r.get("es", "")).strip(), str(r.get("en", "")).strip()
            if not es:
                continue
            c = cards.setdefault(es, {"box": 0, "seen": 0})
            c["box"] = min(c["box"] + 1, len(FLASH_DAYS) - 1) if r.get("known") else 0
            c["due"] = (date.today() + timedelta(days=FLASH_DAYS[c["box"]])).isoformat()
            c["seen"] += 1
            (known if r.get("known") else learning).append(f"{es} — {en}")
        where, n = str(ev.get("set", "")).strip(), len(known) + len(learning)
        append(PROGRESS / "Flashcard Log.md", "# Flashcard Log\nVocabulary Bank flashcard rounds. Generated by the course site.",
               f"- {ts} — **{where}**: knew {len(known)}/{n}" + "".join(f"\n    - still learning: {x}" for x in learning) + "\n")
        state["activity"].append(f"{ts} — flashcards ({where}): knew {len(known)}/{n}")
        return

    wk = int(ev["week"])
    w = state["weeks"].setdefault(str(wk), {})
    title = f"Week {wk} ({BY_WEEK[wk]['title']})"
    was_complete = week_complete(w)

    if kind == "lesson":
        w["lesson_done"] = True
        state["activity"].append(f"{ts} — read lesson for {title}")
    elif kind in ("worksheet", "quiz", "cyber", "drill", "grammar"):
        score, total, missed = int(ev["score"]), int(ev["total"]), ev.get("missed", [])
        label = f"{kind}: {ev['label']}" if ev.get("label") else kind
        w[f"{kind}_attempts"] = w.get(f"{kind}_attempts", 0) + 1
        w[f"{kind}_last"] = score
        w[f"{kind}_best"] = max(score, w.get(f"{kind}_best", 0))
        w[f"{kind}_total"] = total
        w[f"{kind}_missed"] = missed
        pct = round(100 * score / total)
        append(PROGRESS / "Quiz Log.md", "# Quiz Log\nEvery worksheet and quiz attempt, with missed items. Generated by the course site.",
               f"- {ts} — **{title} {label}**: {score}/{total} ({pct}%)" + fmt_missed(missed) + "\n")
        state["activity"].append(f"{ts} — {title} {label}: {score}/{total} ({pct}%)")
    elif kind == "practice":
        text = ev.get("text", "").strip()
        w["practice_done"] = True
        if text:
            w["practice_entries"] = w.get("practice_entries", 0) + 1
            append(VAULT / "Practice" / f"{note_name(BY_WEEK[wk])} - Practice.md",
                   f"# {note_name(BY_WEEK[wk])} — Practice\nTask: {BY_WEEK[wk]['practice']}\n\nBack to [[{note_name(BY_WEEK[wk])}]]",
                   f"## {ts}\n{text}\n\n")
            state["activity"].append(f"{ts} — saved practice writing for {title}")
        else:
            state["activity"].append(f"{ts} — marked practice done for {title}")
    else:
        raise ValueError(f"unknown event type {kind!r}")

    if week_complete(w) and not was_complete:
        w["completed"] = ts[:10]
        state["activity"].append(f"{ts} — ✅ completed {title}")
    state["activity"] = state["activity"][-50:]


def score_cell(w, kind):
    if not w.get(f"{kind}_attempts"):
        return "—"
    return f"{w[f'{kind}_best']}/{w[f'{kind}_total']} ({w[f'{kind}_attempts']}×)"


def write_dashboard(state):
    cur = current_week(state)
    cw = BY_WEEK[cur]
    done = sum(week_complete(state["weeks"].get(str(w["week"]), {})) for w in COURSE)
    minutes = sum(s["minutes"] for s in state["sessions"])
    lines = [
        "---", f"updated: {now()}", f"current_week: {cur}", f"weeks_completed: {done}",
        f"total_study_minutes: {minutes}", "---",
        "# Spanish Progress Dashboard",
        "> Auto-generated by the course site — edits here get overwritten. Notes go in [[Home|My Notes]].",
        "",
        f"**Current week:** {cur} — [[{note_name(cw)}]]  ",
        f"**Weeks completed:** {done}/{len(COURSE)}  ",
        f"**Study time:** {minutes} min over {len(state['sessions'])} sessions  ",
        f"**Started:** {state['started']}",
        "",
        "## Weeks",
        "| Week | Topic | Lesson | Worksheet (best) | Quiz (best) | Cyber vocab (best) | Grammar check (best) | Practice | Status |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in COURSE:
        w = state["weeks"].get(str(c["week"]), {})
        if week_complete(w):
            status = f"✅ {w.get('completed', '')}"
        elif c["week"] == cur:
            status = "▶ current"
        elif w:
            status = "in progress"
        else:
            status = ""
        lines.append(f"| {c['week']} | [[{note_name(c)}\\|{c['title']}]] | {'✔' if w.get('lesson_done') else ''} | "
                     f"{score_cell(w, 'worksheet')} | {score_cell(w, 'quiz')} | {score_cell(w, 'cyber')} | {score_cell(w, 'grammar')} | {'✔' if w.get('practice_done') else ''} | {status} |")

    if not week_complete(state["weeks"].get(str(cur), {})):
        w = state["weeks"].get(str(cur), {})
        todo = [label for key, label in [("lesson_done", "read the lesson"), ("worksheet_attempts", "do the worksheet"),
                                          ("practice_done", "do the practice task")] if not w.get(key)]
        if not (w.get("quiz_total") and w.get("quiz_best", 0) / w["quiz_total"] >= PASS_QUIZ):
            todo.append("score ≥ 80% on the quiz")
        lines += ["", f"## To finish week {cur}", *[f"- [ ] {t}" for t in todo]]

    weak = []
    for c in COURSE:
        w = state["weeks"].get(str(c["week"]), {})
        for kind in ("worksheet", "quiz", "cyber", "drill", "grammar"):
            for m in w.get(f"{kind}_missed", []):
                weak.append(f"- Week {c['week']} {kind}: {m['q']} — answered *{m.get('given') or '—'}*, correct **{m['correct']}**")
    lines += ["", "## Weak spots (missed on most recent attempts)", *(weak[-20:] or ["- None yet"])]
    lines += ["", "## Recent activity", *([f"- {a}" for a in reversed(state["activity"][-12:])] or ["- Nothing yet"])]
    lines += ["", "See also: [[Quiz Log]] · [[Study Log]] · [[Tutor Notes]]", ""]
    PROGRESS.mkdir(parents=True, exist_ok=True)
    (PROGRESS / "Dashboard.md").write_text("\n".join(lines), encoding="utf-8")


class Handler(SimpleHTTPRequestHandler):
    def log_message(self, fmt, *args):
        pass

    def send_json(self, obj, code=200):
        body = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def state_payload(self, state):
        return {**state, "current_week": current_week(state),
                "complete": {c["week"]: week_complete(state["weeks"].get(str(c["week"]), {})) for c in COURSE}}

    def translate_path(self, path):
        # /media/* is served from the vault so photos and audio live in one place
        if path.startswith("/media/"):
            rel = Path(urllib.parse.unquote(path.split("?")[0][len("/media/"):]))
            target = (VAULT / "Media" / rel).resolve()
            if (VAULT / "Media").resolve() in target.parents:
                return str(target)
        return super().translate_path(path)

    def say(self, text, voice="mx"):
        """An es-MX clip for `text`, made with the same voice as the course audio the first time it's asked for, then cached."""
        text = text.strip()
        if not text or len(text) > 200 or voice not in SAY_VOICES:
            return self.send_json({"error": "bad text"}, 400)
        path = SAY_DIR / ((hashlib.sha1(text.encode()).hexdigest()[:12]) + ("" if voice == "mx" else "-" + voice) + ".mp3")
        if not path.exists():
            SAY_DIR.mkdir(parents=True, exist_ok=True)
            tmp = path.with_suffix(".part")
            with SAY_SLOTS:
                r = subprocess.run([str(HERE / ".venv" / "bin" / "python"), "-c", SAY_CODE, text, str(tmp), SAY_VOICES[voice]], capture_output=True, timeout=30)
            if r.returncode or not tmp.exists():
                tmp.unlink(missing_ok=True)
                return self.send_json({"error": "voice unavailable"}, 502)
            tmp.rename(path)
        body = path.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", "audio/mpeg")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "max-age=31536000")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path == "/api/state":
            with LOCK:
                return self.send_json(self.state_payload(load_state()))
        if self.path.startswith("/api/say?"):
            q = urllib.parse.parse_qs(urllib.parse.urlsplit(self.path).query)
            return self.say(q.get("t", [""])[0], q.get("v", ["mx"])[0])
        super().do_GET()

    def do_POST(self):
        if self.path != "/api/event":
            return self.send_json({"error": "not found"}, 404)
        try:
            ev = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
            with LOCK:
                state = load_state()
                apply_event(state, ev)
                save_state(state)
                write_dashboard(state)
                return self.send_json(self.state_payload(state))
        except (ValueError, KeyError, IndexError) as e:
            return self.send_json({"error": str(e)}, 400)


def main():
    if "--regen" in sys.argv:
        write_dashboard(load_state())
        print(f"Regenerated {PROGRESS / 'Dashboard.md'}")
        return
    if not STATE_FILE.exists():
        save_state(load_state())
    write_dashboard(load_state())
    url = f"http://127.0.0.1:{PORT}"
    server = ThreadingHTTPServer(("127.0.0.1", PORT), partial(Handler, directory=str(HERE / "site")))
    print(f"Spanish course running at {url}  (Ctrl+C to stop)\nSaving progress to {PROGRESS}")
    if "--open" in sys.argv:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
