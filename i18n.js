const LANG = (() => {
  try { const s = localStorage.getItem('ui-lang'); if (s === 'es' || s === 'en') return s; } catch {}
  return /^es\b/i.test(navigator.language || '') ? 'es' : 'en';  // Spanish browsers start in Spanish
})();
function setLang(l) { try { localStorage.setItem('ui-lang', l); } catch {} location.reload(); }

function T(s, v) {
  let t = (LANG === 'es' && ES[s]) || s;
  if (v) t = t.replace(/\{(\w+)\}/g, (_, k) => v[k]);
  return t;
}

